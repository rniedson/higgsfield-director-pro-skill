#!/usr/bin/env python3
"""Soma os registros de calibração às cegas (calibracao/*.json) no placar dos dois READMEs.

Uso: python3 tools/agregar_calibracao.py              # imprime o placar em português
     python3 tools/agregar_calibracao.py --escrever   # atualiza README.md e README.pt-BR.md entre os marcadores
     python3 tools/agregar_calibracao.py --checar     # sai com 1 se um registro é inválido ou o README está velho
Só lê e escreve arquivos do repositório; não acessa a rede.
"""
import json
import re
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parent.parent
PASTA = RAIZ / "calibracao"
sys.path.insert(0, str(RAIZ / "higgsfield-director" / "scripts"))
import hfd  # noqa: E402

INICIO, FIM = "<!-- calibracao:inicio -->", "<!-- calibracao:fim -->"
NOME = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z-]+)-([a-z0-9]{1,12})\.json$")
ROTULOS = {
    "pt": {"anuncio-produto": "Anúncio de produto", "cena-com-personagem": "Cena com personagem",
           "trailer": "Trailer", "institucional": "Institucional", "clipe": "Clipe musical", "loop": "Loop",
           "imagem": "Imagem", "outro": "Outro"},
    "en": {"anuncio-produto": "Product ad", "cena-com-personagem": "Character scene", "trailer": "Trailer",
           "institucional": "Corporate", "clipe": "Music clip", "loop": "Loop", "imagem": "Image",
           "outro": "Other"},
}
TEXTO = {
    "pt": {"cab": "| Tipo de pedido | Rodadas | Escolheu com a skill | Escolheu sem | Empate | Nota do avaliador cego, com × sem |",
           "total": "**Total**", "vazio": "Nenhum registro ainda.",
           "versao": "Por versão da skill", "rodadas": "rodada(s)",
           "ordem": "A versão vista primeiro foi a escolhida em {g} de {n} rodada(s) com a ordem registrada.",
           "fonte": "Gerado por `tools/agregar_calibracao.py` a partir de {n} registro(s) em `calibracao/`."},
    "en": {"cab": "| Request type | Rounds | Chose with the skill | Chose without | Tie | Blind reviewer score, with × without |",
           "total": "**Total**", "vazio": "No records yet.",
           "versao": "By skill version", "rodadas": "round(s)",
           "ordem": "The version seen first was chosen in {g} of {n} round(s) with the order recorded.",
           "fonte": "Generated by `tools/agregar_calibracao.py` from {n} record(s) in `calibracao/`."},
}


def carregar():
    """Devolve (registros, problemas). Cada problema já vem com o nome do arquivo."""
    registros, problemas = [], []
    for arq in sorted(PASTA.glob("*")) if PASTA.exists() else []:
        if arq.name == "README.md":
            continue
        m = NOME.match(arq.name)
        if not m:
            problemas.append(f"calibracao/{arq.name}: nome fora do padrão AAAA-MM-DD-<categoria>-<sufixo>.json")
            continue
        try:
            reg = json.loads(arq.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError) as e:
            problemas.append(f"calibracao/{arq.name}: JSON inválido: {e}")
            continue
        erros = hfd.checar_registro(reg)
        if not erros and (reg["data"] != m.group(1) or reg["categoria"] != m.group(2)):
            erros = ["a data e a categoria do nome devem ser as do registro"]
        problemas += [f"calibracao/{arq.name}: {e}" for e in erros]
        if not erros:
            registros.append(reg)
    return registros, problemas


def _num(v, idioma):
    s = f"{v:.1f}"
    return s.replace(".", ",") if idioma == "pt" else s


def placar(registros, idioma):
    t, rot = TEXTO[idioma], ROTULOS[idioma]
    if not registros:
        return t["vazio"]
    linhas = [t["cab"], "|---|---:|---:|---:|---:|---|"]
    tot = {"n": 0, "com": 0, "sem": 0, "empate": 0}
    for cat in hfd.CATEGORIAS:
        rs = [r for r in registros if r["categoria"] == cat]
        if not rs:
            continue
        c = {v: sum(r["voto"] == v for r in rs) for v in ("com", "sem", "empate")}
        notas = [r["notas"] for r in rs if set(r.get("notas", {})) == {"com", "sem"}]
        if notas:
            media = {k: sum(n[k]["total"] for n in notas) / len(notas) for k in ("com", "sem")}
            nota = f"{_num(media['com'], idioma)} × {_num(media['sem'], idioma)} ({len(notas)})"
        else:
            nota = "—"
        linhas.append(f"| {rot[cat]} | {len(rs)} | {c['com']} | {c['sem']} | {c['empate']} | {nota} |")
        tot["n"] += len(rs)
        for v in c:
            tot[v] += c[v]
    linhas.append(f"| {t['total']} | {tot['n']} | {tot['com']} | {tot['sem']} | {tot['empate']} | |")
    versoes = {}
    for r in registros:
        versoes.setdefault(r["versao_skill"], []).append(r["voto"])
    partes = []
    for v, votos in versoes.items():
        com, sem = votos.count("com"), votos.count("sem")
        partes.append(f"`{v}`: {com} × {sem}" + (f" ({votos.count('empate')} =)" if "empate" in votos else ""))
    linhas += ["", f"{t['versao']} ({'com × sem' if idioma == 'pt' else 'with × without'}): " + "; ".join(partes)
               + "."]
    ordem = [r for r in registros if r.get("visto_primeiro") in ("com", "sem") and r["voto"] != "empate"]
    if ordem:
        g = sum(r["visto_primeiro"] == r["voto"] for r in ordem)
        linhas += ["", t["ordem"].format(g=g, n=len(ordem))]
    linhas += ["", t["fonte"].format(n=len(registros))]
    return "\n".join(linhas)


def readme_atualizado(arq, idioma, registros):
    texto = arq.read_text(encoding="utf-8")
    if texto.count(INICIO) != 1 or texto.count(FIM) != 1 or texto.index(INICIO) > texto.index(FIM):
        return None, texto
    antes, resto = texto.split(INICIO)
    _, depois = resto.split(FIM)
    return antes + INICIO + "\n" + placar(registros, idioma) + "\n" + FIM + depois, texto


def checar(problemas):
    """Usado também por tools/checar_repo.py."""
    registros, erros = carregar()
    problemas += erros
    for nome, idioma in (("README.md", "en"), ("README.pt-BR.md", "pt")):
        novo, atual = readme_atualizado(RAIZ / nome, idioma, registros)
        if novo is None:
            problemas.append(f"{nome}: faltam os marcadores {INICIO} e {FIM}, nesta ordem")
        elif novo != atual:
            problemas.append(f"{nome}: o placar da calibração está desatualizado; rode tools/agregar_calibracao.py "
                             "--escrever")
    return registros


def main(argv):
    if "--checar" in argv:
        problemas = []
        checar(problemas)
        for p in problemas:
            print(p)
        print(f"{len(problemas)} problema(s)" if problemas else "ok: registros e placar")
        return 1 if problemas else 0
    registros, problemas = carregar()
    for p in problemas:
        print(p, file=sys.stderr)
    if problemas:
        return 1
    if "--escrever" in argv:
        for nome, idioma in (("README.md", "en"), ("README.pt-BR.md", "pt")):
            novo, atual = readme_atualizado(RAIZ / nome, idioma, registros)
            if novo is None:
                print(f"{nome}: faltam os marcadores {INICIO} e {FIM}", file=sys.stderr)
                return 1
            if novo != atual:
                (RAIZ / nome).write_text(novo, encoding="utf-8")
                print(f"atualizado: {nome}")
        return 0
    print(placar(registros, "pt"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
