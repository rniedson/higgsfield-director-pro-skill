#!/usr/bin/env python3
"""Adds up the blind calibration records (calibration/*.json) into the scoreboard of calibration/README.md.

Usage: python3 tools/aggregate_calibration.py           # prints the scoreboard
       python3 tools/aggregate_calibration.py --write   # updates calibration/README.md between the markers
       python3 tools/aggregate_calibration.py --check   # exits with 1 if a record is invalid or the page is stale
It only reads and writes files of the repository; it does not touch the network.
Records with the old 5.x field names or values still load in 6.x, with a warning on stderr.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FOLDER = ROOT / "calibration"
sys.path.insert(0, str(ROOT / "higgsfield-director" / "scripts"))
import hfd  # noqa: E402

START, END = "<!-- calibration:start -->", "<!-- calibration:end -->"
# The page that carries the scoreboard. Until 2026-11-26 it was both READMEs; they no longer report the rounds.
TARGETS = (("calibration/README.md", "en"),)
NAME = re.compile(r"^(\d{4}-\d{2}-\d{2})-([a-z-]+)-([a-z0-9]{1,12})\.json$")
LABELS = {
    "en": {"product-ad": "Product ad", "character-scene": "Character scene", "trailer": "Trailer",
           "corporate": "Corporate", "music-video": "Music video", "loop": "Loop", "image": "Image",
           "other": "Other"},
}
TEXT = {
    "en": {"header": "| Request type | Rounds | Chose with the skill | Chose without | Tie | Blind reviewer score, with × without |",
           "total": "**Total**", "empty": "No records yet.",
           "version": "By skill version", "rounds": "round(s)",
           "order": "The version seen first was chosen in {g} of {n} round(s) with the order recorded.",
           "source": "Generated by `tools/aggregate_calibration.py` from {n} record(s) in `calibration/`."},
}


def _warn(message):
    print(f"warning: {message}", file=sys.stderr)


def load():
    """Returns (records, problems). Each problem already carries the file name."""
    records, problems = [], []
    # the files git would publish: an ignored .DS_Store is not a record
    from public_boundary import published_files
    names = [p for p in published_files(ROOT) if p.startswith("calibration/")]
    for p in names:
        f = ROOT / p
        if p.count("/") > 1:
            problems.append(f"{p}: a record goes directly in calibration/, not in a subfolder")
            continue
        if f.name == "README.md":
            continue
        where = f"calibration/{f.name}"
        m = NAME.match(f.name)
        if not m:
            problems.append(f"{where}: name outside the pattern YYYY-MM-DD-<category>-<suffix>.json")
            continue
        category = m.group(2)
        if category in hfd.OLD_CATEGORIES:  # 6.x only
            _warn(f"{where}: '{category}' in the file name is the old name of '{hfd.OLD_CATEGORIES[category]}'; "
                  "rename the file, the old name will be removed in 7.0")
            category = hfd.OLD_CATEGORIES[category]
        try:
            rec = json.loads(f.read_text(encoding="utf-8"))
        except (ValueError, UnicodeDecodeError) as e:
            problems.append(f"{where}: invalid JSON: {e}")
            continue
        try:
            rec, found = hfd.translate_record(rec, where)
        except hfd.Error as e:
            problems.append(str(e))
            continue
        if found:
            _warn(hfd.old_names_warning(where, found))
        errors = hfd.check_record(rec)
        if not errors and (rec["date"] != m.group(1) or rec["category"] != category):
            errors = ["the date and the category in the name must be those of the record"]
        problems += [f"{where}: {e}" for e in errors]
        if not errors:
            records.append(rec)
    return records, problems


def _num(v, language):
    return f"{v:.1f}"


def scoreboard(records, language):
    t, labels = TEXT[language], LABELS[language]
    if not records:
        return t["empty"]
    lines = [t["header"], "|---|---:|---:|---:|---:|---|"]
    tot = {"n": 0, "with": 0, "without": 0, "tie": 0}
    for cat in hfd.CATEGORIES:
        rs = [r for r in records if r["category"] == cat]
        if not rs:
            continue
        c = {v: sum(r["vote"] == v for r in rs) for v in ("with", "without", "tie")}
        scores = [r["scores"] for r in rs if set(r.get("scores", {})) == {"with", "without"}]
        if scores:
            mean = {k: sum(s[k]["total"] for s in scores) / len(scores) for k in ("with", "without")}
            score = f"{_num(mean['with'], language)} × {_num(mean['without'], language)} ({len(scores)})"
        else:
            score = "—"
        lines.append(f"| {labels[cat]} | {len(rs)} | {c['with']} | {c['without']} | {c['tie']} | {score} |")
        tot["n"] += len(rs)
        for v in c:
            tot[v] += c[v]
    lines.append(f"| {t['total']} | {tot['n']} | {tot['with']} | {tot['without']} | {tot['tie']} | |")
    versions = {}
    for r in records:
        versions.setdefault(r["skill_version"], []).append(r["vote"])
    parts = []
    for v, votes in versions.items():
        w, wo = votes.count("with"), votes.count("without")
        parts.append(f"`{v}`: {w} × {wo}" + (f" ({votes.count('tie')} =)" if "tie" in votes else ""))
    lines += ["", f"{t['version']} (with × without): " + "; ".join(parts) + "."]
    order = [r for r in records if r.get("seen_first") in ("with", "without") and r["vote"] != "tie"]
    if order:
        g = sum(r["seen_first"] == r["vote"] for r in order)
        lines += ["", t["order"].format(g=g, n=len(order))]
    lines += ["", t["source"].format(n=len(records))]
    return "\n".join(lines)


def updated_readme(f, language, records):
    text = f.read_text(encoding="utf-8")
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        return None, text
    before, rest = text.split(START)
    _, after = rest.split(END)
    return before + START + "\n" + scoreboard(records, language) + "\n" + END + after, text


def check(problems):
    """Also used by tools/check_repo.py."""
    records, errors = load()
    problems += errors
    for name, language in TARGETS:
        new, current = updated_readme(ROOT / name, language, records)
        if new is None:
            problems.append(f"{name}: the markers {START} and {END} are missing, in this order")
        elif new != current:
            problems.append(f"{name}: the calibration scoreboard is out of date; run tools/aggregate_calibration.py "
                            "--write")
    return records


def main(argv):
    if "--check" in argv:
        problems = []
        check(problems)
        for p in problems:
            print(p)
        print(f"{len(problems)} problem(s)" if problems else "ok: records and scoreboard")
        return 1 if problems else 0
    records, problems = load()
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        return 1
    if "--write" in argv:
        for name, language in TARGETS:
            new, current = updated_readme(ROOT / name, language, records)
            if new is None:
                print(f"{name}: the markers {START} and {END} are missing", file=sys.stderr)
                return 1
            if new != current:
                (ROOT / name).write_text(new, encoding="utf-8")
                print(f"updated: {name}")
        return 0
    print(scoreboard(records, "en"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
